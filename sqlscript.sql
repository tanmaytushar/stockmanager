-- Portfolio details with current asset value
SELECT
    C.CUSTOMER_NAME,
    P.STOCK_SYMBOL,
    P.QUANTITY,
    S.CURRENT_PRICE,
    P.QUANTITY * S.CURRENT_PRICE AS TOTAL_ASSET_VALUE
FROM CUSTOMER_PORTFOLIO P
JOIN CUSTOMER C
    ON C.CUSTOMER_ID = P.CUSTOMER_ID
JOIN STOCK S
    ON S.STOCK_SYMBOL = P.STOCK_SYMBOL
ORDER BY C.CUSTOMER_NAME;
