-- ============================================================
-- 1. STOCK TABLE
-- ============================================================

CREATE TABLE STOCK (
    STOCK_SYMBOL       VARCHAR2(10) PRIMARY KEY,
    STOCK_NAME         VARCHAR2(100) NOT NULL,
    CURRENT_PRICE      NUMBER(10,2) NOT NULL,
    AVAILABLE_QUANTITY NUMBER(10) NOT NULL,

    CONSTRAINT CHK_STOCK_PRICE
        CHECK (CURRENT_PRICE > 0),

    CONSTRAINT CHK_STOCK_QUANTITY
        CHECK (AVAILABLE_QUANTITY >= 0)
);

-- ============================================================
-- 2. CUSTOMER TABLE
-- ============================================================

CREATE TABLE CUSTOMER (
    CUSTOMER_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CUSTOMER_NAME VARCHAR2(100) NOT NULL,
    EMAIL_ADDRESS VARCHAR2(150) NOT NULL UNIQUE
);

-- ============================================================
-- 3. STOCK TRANSACTION TABLE
-- ============================================================

CREATE TABLE STOCK_TRANSACTION (
    TRANSACTION_ID NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CUSTOMER_ID NUMBER NOT NULL,
    STOCK_SYMBOL VARCHAR2(10) NOT NULL,
    TRANSACTION_TYPE VARCHAR2(4) NOT NULL,
    QUANTITY NUMBER(10) NOT NULL,
    PRICE NUMBER(10,2) NOT NULL,
    TRANSACTION_DATE TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT FK_TRANSACTION_CUSTOMER
        FOREIGN KEY (CUSTOMER_ID)
        REFERENCES CUSTOMER (CUSTOMER_ID),

    CONSTRAINT FK_TRANSACTION_STOCK
        FOREIGN KEY (STOCK_SYMBOL)
        REFERENCES STOCK (STOCK_SYMBOL),

    CONSTRAINT CHK_TRANSACTION_TYPE
        CHECK (TRANSACTION_TYPE IN ('BUY', 'SELL')),

    CONSTRAINT CHK_TRANSACTION_QUANTITY
        CHECK (QUANTITY > 0),

    CONSTRAINT CHK_TRANSACTION_PRICE
        CHECK (PRICE > 0)
);

-- ============================================================
-- 4. CUSTOMER PORTFOLIO TABLE
-- ============================================================

CREATE TABLE CUSTOMER_PORTFOLIO (
    CUSTOMER_ID NUMBER NOT NULL,
    STOCK_SYMBOL VARCHAR2(10) NOT NULL,
    QUANTITY NUMBER(10) NOT NULL,

    CONSTRAINT PK_CUSTOMER_PORTFOLIO
        PRIMARY KEY (CUSTOMER_ID, STOCK_SYMBOL),

    CONSTRAINT FK_PORTFOLIO_CUSTOMER
        FOREIGN KEY (CUSTOMER_ID)
        REFERENCES CUSTOMER (CUSTOMER_ID),

    CONSTRAINT FK_PORTFOLIO_STOCK
        FOREIGN KEY (STOCK_SYMBOL)
        REFERENCES STOCK (STOCK_SYMBOL),

    CONSTRAINT CHK_PORTFOLIO_QUANTITY
        CHECK (QUANTITY > 0)
);

-- Index foreign-key columns used by transaction and portfolio queries.
CREATE INDEX IDX_TRANSACTION_CUSTOMER
    ON STOCK_TRANSACTION (CUSTOMER_ID);

CREATE INDEX IDX_TRANSACTION_STOCK
    ON STOCK_TRANSACTION (STOCK_SYMBOL);

CREATE INDEX IDX_PORTFOLIO_STOCK
    ON CUSTOMER_PORTFOLIO (STOCK_SYMBOL);

